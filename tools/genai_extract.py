"""Builds lib/genai/content.ts from tools/genai-playbook.html (harsh's Gen AI Engineer Playbook).
Each <section class="module"> becomes one entry: its head (eyebrow, title, lede, chips) as fields and
its slides as an HTML string. Classes are prefixed gx- so they never collide with the app's own;
each slide also gets .card so picture themes give it glass. Run: python3 tools/genai_extract.py"""
import html, json, re

src = open("tools/genai-playbook.html", encoding="utf-8").read()
rail = dict(re.findall(r'<a href="#([\w-]+)"[^>]*><span class="num">[^<]*</span>([^<]+)<', src))

def text(s):  # strip tags, unescape
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()

def prefix(m):
    out = []
    for c in m.group(1).split():
        out.append(c if c.startswith("language-") or c == "mermaid" else "gx-" + c)
    if "gx-slide" in out: out.insert(0, "card")
    return 'class="' + " ".join(out) + '"'

out = []
for m in re.finditer(r'<section class="module" id="([\w-]+)"[^>]*>(.*?)\n</section>', src, re.S):
    sid, body = m.group(1), m.group(2)
    if sid == "start":
        head = re.search(r'<div class="hero">(.*?)</div>\s*</div>', body, re.S).group(0)
        eyebrow, title = text(re.search(r'class="eyebrow">(.*?)</span>', head).group(1)), "Start here"
        lede = text(re.search(r'class="lede">(.*?)</p>', head, re.S).group(1)); chips = []
    else:
        head = re.search(r'<div class="module-head">.*?\n  </div>', body, re.S).group(0)
        eyebrow = text(re.sub(r"<label.*?</label>", "", re.search(r'class="eyebrow">(.*?)</div>', head, re.S).group(1)))
        title = text(re.search(r"<h2>(.*?)</h2>", head, re.S).group(1))
        lp = re.search(r"<p>(.*?)</p>", head, re.S); lede = text(lp.group(1)) if lp else ""
        chips = [text(c) for c in re.findall(r'<span class="chip">(.*?)</span>', head)]
    rest = body[body.index(head) + len(head):].strip()
    rest = re.sub(r'class="([^"]*)"', prefix, rest)
    rest = rest.replace('style="color:var(--ink);font-weight:600"', 'class="gx-strong"')
    # mermaid reads the pre's text, so its <br/> line breaks must stay text instead of becoming <br> elements
    rest = re.sub(r'<pre class="mermaid">.*?</pre>', lambda m: re.sub(r"<br\s*/?>", "&lt;br/&gt;", m.group(0)), rest, flags=re.S)
    rest = re.sub(r'\s*<p class="gx-footer">.*?</p>', "", rest, flags=re.S)  # browser-only progress note; ticks sync here
    rest = rest.replace("Your progress is saved in this browser.", "It syncs to your account.")
    # number the slides so the page can link to them, and list them as the page's contents
    k = iter(range(1, 1000))
    rest = re.sub(r'<article class="card gx-slide', lambda m: f'<article id="s-{next(k)}" class="card gx-slide', rest)
    toc = [{"id": a, "tag": text(t), "title": text(h)} for a, t, h in
           re.findall(r'<article id="(s-\d+)".*?class="gx-slide-tag"><b>(.*?)</b>.*?<h3>(.*?)</h3>', rest, re.S)]
    out.append({"id": sid, "toc": toc, "nav": text(rail.get(sid, title)), "eyebrow": eyebrow, "title": title, "lede": lede, "chips": chips,
                "module": sid.startswith("m") and sid[1:].isdigit(), "html": rest})

ts = ("// Generated by tools/genai_extract.py from tools/genai-playbook.html. Do not edit by hand.\n"
      "export type GSection = { id: string; toc: { id: string; tag: string; title: string }[]; nav: string; eyebrow: string; title: string; lede: string; chips: string[]; module: boolean; html: string };\n"
      "export const GENAI: GSection[] = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
open("lib/genai/content.ts", "w", encoding="utf-8").write(ts)
print(len(out), "sections", [(o["id"], o["nav"], len(o["html"])) for o in out])

# TensorFlow versions of the PyTorch code blocks, keyed by the PyTorch file name they mirror.
# Each file in tools/genai_tf runs on its own; tools/genai_tf/check.py tests them all.
import pathlib
tf = {}
for f in sorted(pathlib.Path("tools/genai_tf").glob("*.py")):
    if f.name == "check.py": continue
    shown = "mlp_keras.py" if f.name == "mlp_torch.py" else f.stem + "_tf.py"
    tf[f.name] = {"file": shown, "code": f.read_text(encoding="utf-8").rstrip() + "\n"}
open("lib/genai/tensorflow.ts", "w", encoding="utf-8").write(
    "// Generated by tools/genai_extract.py from tools/genai_tf/*.py. Do not edit by hand.\n"
    "export const TF: Record<string, { file: string; code: string }> = " + json.dumps(tf, ensure_ascii=False, indent=1) + ";\n")
print(len(tf), "TensorFlow labs")
